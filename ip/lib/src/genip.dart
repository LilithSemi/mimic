/// The `mimic_genip` generator, as value objects.
///
/// [MimicGenIpConfig] holds what the command line states and derives
/// everything else: the build target, the SoC, the nextpnr pre-place script
/// and the `mimic.json` manifest. `bin/mimic_genip.dart` only parses arguments
/// into this class and prints the summary, so every derivation here is
/// reachable from a unit test.
